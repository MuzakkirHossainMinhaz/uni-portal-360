import mongoose, { Schema } from 'mongoose';
import { Days } from './offeredCourse.constant';
import type { TOfferedCourse } from './offeredCourse.interface';

const offeredCourseSchema = new mongoose.Schema<TOfferedCourse>(
  {
    semesterRegistration: {
      type: Schema.Types.ObjectId,
      required: true,
      ref: 'SemesterRegistration',
    },
    academicSemester: {
      type: Schema.Types.ObjectId,
      required: true,
      ref: 'AcademicSemester',
    },
    academicFaculty: {
      type: Schema.Types.ObjectId,
      required: true,
      ref: 'AcademicFaculty',
    },
    academicDepartment: {
      type: Schema.Types.ObjectId,
      required: true,
      ref: 'AcademicDepartment',
    },
    course: {
      type: Schema.Types.ObjectId,
      required: true,
      ref: 'Course',
    },
    faculty: {
      type: Schema.Types.ObjectId,
      required: true,
      ref: 'Faculty',
    },
    facultyTransfers: {
      type: [{ from: Schema.Types.ObjectId, to: Schema.Types.ObjectId, reason: String, transferredAt: Date }],
      default: [],
    },
    maxCapacity: {
      type: Number,
      required: true,
    },
    section: {
      type: Number,
      required: true,
    },
    days: [
      {
        type: String,
        enum: Days,
      },
    ],
    startTime: {
      type: String,
      required: true,
    },
    endTime: {
      type: String,
      required: true,
    },
  },
  {
    timestamps: true,
  },
);

offeredCourseSchema.index({ semesterRegistration: 1, course: 1, section: 1 }, { unique: true });

export const OfferedCourse = mongoose.model<TOfferedCourse>('OfferedCourse', offeredCourseSchema);
